'''
算术运算符大乱斗
对应知识点： 算术运算符：+ - * / // % **。
任务：
假设你有一笔零花钱 money = 105，一包零食的价格是 price = 10。

计算你能买多少包完整的零食（用整除 //）。

计算买完后还剩下多少钱（用取余 %）。

假设你每天能得到 2 块钱，计算 5 天后你的钱变成了多少（用幂运算 ** 或者乘法，验证一下）。
(提示：请用 print() 加上 f-string 把结果打印得好看一点，比如 “你能买 10 包，还剩 5 元”)
'''
