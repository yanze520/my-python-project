'''
理解 input 的“真面目”
对应知识点： input() 的返回值默认是字符串。
任务：

用 input() 让用户输入两个数字（比如 10 和 20），分别存到变量 num1 和 num2。

直接打印 num1 + num2 的结果。

再用 type() 函数打印一下 num1 的数据类型，看看会发生什么。
思考：为什么会输出这个结果？
'''
num1=input("请输入一个数字")
num2=input("请再输入一个数字")
print(num1+num2)
print(type(num1))

'''
拯救数学计算（类型转换）
对应知识点： int()、float() 类型转换。
任务：

继续让用户输入两个数字，但这次，你需要把它们转换成整数（int）。

打印这两个数字的和。

再让用户输入一个带小数点的价格（比如 19.99），把它转换成浮点数（float），然后打印这个价格乘以 2 的结果。
'''

print(int(num1)+int(num2))

num3=input("请输入一个小数")
